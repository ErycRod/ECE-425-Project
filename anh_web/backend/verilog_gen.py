"""Advanced level ("Create"): write the Verilog and the build commands for a user's design.

make_top() returns a top-level module that instantiates the team's parameterized
hw/rtl/systolic_array.v with the user's P and B, with a header that records the predicted
numbers (a small "design sheet"). commands() returns the exact commands that simulate and
synthesize that configuration with the repo's own scripts (hw/scripts/run_tb.py and
hw/scripts/synth_one.tcl), so a user can take the design all the way to Vivado.
"""


def acc_bits(bits):
    """Accumulator width used by systolic_array.v (safe for K up to 8191)."""
    return 2 * bits + 12


def module_name(P, bits):
    return "edgevlm_top_p" + str(P) + "_b" + str(bits)


def file_name(P, bits):
    return module_name(P, bits) + ".v"


def make_top(P, bits, sheet=None):
    """Verilog text for a top module wrapping systolic_array with this P and B.

    sheet (optional) is a list of short lines for the header, e.g. predicted LUTs and TTFT.
    """
    name = module_name(P, bits)
    acc = acc_bits(bits)
    pes = P * P

    header = [
        "// " + file_name(P, bits) + " - generated by EdgeVLM Lab (Advanced level)",
        "//",
        "// A {P} x {P} output-stationary systolic array ({pes} PEs), {bits}-bit signed operands,".format(
            P=P, pes=pes, bits=bits),
        "// {acc}-bit accumulators (2*B + 12, safe for K up to 8191).".format(acc=acc),
    ]
    if sheet:
        header.append("//")
        for text in sheet:
            header.append("// " + text)
    header += [
        "//",
        "// Needs hw/rtl/systolic_array.v and hw/rtl/mac_pe.v from the EdgeVLM repo.",
        "// Each cycle with in_valid=1, feed one column of A on a_col and one row of B on b_row",
        "// (element i in bits [i*B +: B]). The P x P results are final when busy falls,",
        "// K + 2P - 2 cycles after the first input; c_flat holds them row-major, ACC bits each.",
    ]

    body = """`timescale 1ns / 1ps

module {name} #(
    parameter P   = {P},
    parameter B   = {bits},
    parameter ACC = 2 * B + 12
) (
    input  wire                 clk,
    input  wire                 rst,
    input  wire                 clear,      // zero all accumulators before a new tile
    input  wire                 in_valid,   // a_col / b_row hold one step of K this cycle
    input  wire [P*B-1:0]       a_col,      // column k of A: P signed B-bit values
    input  wire [P*B-1:0]       b_row,      // row k of B: P signed B-bit values
    output wire [P*P*ACC-1:0]   c_flat,     // the P x P results, row-major
    output wire                 busy        // 1 while data is still moving through the array
);

    systolic_array #(
        .P(P),
        .B(B),
        .ACC(ACC)
    ) u_array (
        .clk(clk),
        .rst(rst),
        .clear(clear),
        .in_valid(in_valid),
        .a_col(a_col),
        .b_row(b_row),
        .c_flat(c_flat),
        .busy(busy)
    );

endmodule
""".format(name=name, P=P, bits=bits)

    return "\n".join(header) + "\n\n" + body


def commands(P, bits):
    """Commands that simulate and synthesize this exact configuration with the repo's scripts."""
    out_dir = "build/custom_P" + str(P) + "_B" + str(bits)
    return {
        "simulate_xsim": "python hw/scripts/run_tb.py --sizes {P} --bits {B}".format(P=P, B=bits),
        "simulate_iverilog": "python hw/scripts/run_tb.py --sim iverilog --sizes {P} --bits {B}".format(P=P, B=bits),
        "synthesize": "vivado -mode batch -source hw/scripts/synth_one.tcl -tclargs {P} {B} {out}".format(
            P=P, B=bits, out=out_dir),
        "reports": out_dir + "/ (utilization.rpt, timing.rpt, power.rpt)",
    }
