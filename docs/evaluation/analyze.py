#!/usr/bin/env python3
"""Summarize the user study: task completion, quiz before vs after, and usability (SUS).

Usage:
  python docs/evaluation/analyze.py docs/evaluation/results.csv
Writes summary.md (tables for the report) and summary.png (chart) next to the CSV.
The CSV has one row per participant, with the columns of results_template.csv.
"""
import csv
import statistics
import sys
from pathlib import Path

TASKS = [
    ("t1", "Beginner quick checks", "Remember / Understand"),
    ("t2", "Read a PE's sum in the animation", "Understand"),
    ("t3", "First word under 1 minute", "Apply"),
    ("t4", "16-bit, over 10 words/s", "Apply"),
    ("t5", "Explain why 8-bit is slower at 4x4", "Analyze"),
    ("t6", "Pick bits within 5 points of accuracy", "Analyze"),
    ("t7", "16-bit design beating the best first word", "Evaluate"),
    ("t8", "Download the Verilog + synth command", "Create"),
]
QUIZ = 6


def number(value):
    try:
        return float(value)
    except (TypeError, ValueError):
        return None


def sus_score(row):
    """Standard SUS: odd items (score - 1), even items (5 - score), sum x 2.5 -> 0..100."""
    total = 0.0
    for i in range(1, 11):
        value = number(row.get("sus%d" % i))
        if value is None:
            return None
        if i % 2 == 1:
            total = total + (value - 1)
        else:
            total = total + (5 - value)
    return total * 2.5


def quiz_score(row, prefix):
    values = [number(row.get("%s_q%d" % (prefix, i))) for i in range(1, QUIZ + 1)]
    if any(v is None for v in values):
        return None
    return sum(values)


def sus_label(score):
    if score >= 80.3:
        return "excellent (top 10%)"
    if score >= 68:
        return "above average"
    if score >= 51:
        return "below average"
    return "poor"


def summarize(rows):
    """All numbers for the report, from the CSV rows."""
    n = len(rows)
    tasks = []
    for key, name, level in TASKS:
        results = [r.get(key + "_result", "").strip().lower() for r in rows]
        times = [number(r.get(key + "_time_s")) for r in rows]
        times = [t for t in times if t is not None]
        tasks.append({
            "key": key, "name": name, "level": level,
            "success": results.count("success"),
            "hint": results.count("hint"),
            "fail": results.count("fail"),
            "median_time_s": statistics.median(times) if times else None,
        })

    pre = [quiz_score(r, "pre") for r in rows]
    post = [quiz_score(r, "post") for r in rows]
    pairs = [(a, b) for a, b in zip(pre, post) if a is not None and b is not None]
    per_question = []
    for i in range(1, QUIZ + 1):
        before = [number(r.get("pre_q%d" % i)) for r in rows]
        after = [number(r.get("post_q%d" % i)) for r in rows]
        before = [v for v in before if v is not None]
        after = [v for v in after if v is not None]
        per_question.append({
            "question": i,
            "pre_pct": 100 * sum(before) / len(before) if before else None,
            "post_pct": 100 * sum(after) / len(after) if after else None,
        })

    sus = [s for s in (sus_score(r) for r in rows) if s is not None]
    learning = []
    for i in range(11, 14):
        values = [number(r.get("learn%d" % i)) for r in rows]
        values = [v for v in values if v is not None]
        learning.append({"item": i, "mean": statistics.mean(values) if values else None})

    return {
        "n": n,
        "tasks": tasks,
        "quiz": {
            "pre_mean": statistics.mean([p[0] for p in pairs]) if pairs else None,
            "post_mean": statistics.mean([p[1] for p in pairs]) if pairs else None,
            "improved": sum(1 for a, b in pairs if b > a),
            "pairs": len(pairs),
            "per_question": per_question,
        },
        "sus": {
            "mean": statistics.mean(sus) if sus else None,
            "min": min(sus) if sus else None,
            "max": max(sus) if sus else None,
            "label": sus_label(statistics.mean(sus)) if sus else None,
        },
        "learning": learning,
        "comments": [r["comments"].strip() for r in rows if r.get("comments", "").strip()],
    }


def fmt(value, digits=1):
    if value is None:
        return "n/a"
    return ("{:.%df}" % digits).format(value)


def to_markdown(s):
    lines = ["# User evaluation results", "",
             "{} participants. Generated by `docs/evaluation/analyze.py`.".format(s["n"]), "",
             "## Tasks", "",
             "| Task | Bloom's level | Success | With hint | Failed | Median time (s) |",
             "|---|---|---|---|---|---|"]
    for t in s["tasks"]:
        lines.append("| {} {} | {} | {} | {} | {} | {} |".format(
            t["key"].upper(), t["name"], t["level"], t["success"], t["hint"], t["fail"], fmt(t["median_time_s"], 0)))
    q = s["quiz"]
    lines += ["", "## Quiz before vs after ({} questions)".format(QUIZ), "",
              "Mean score: **{} before → {} after** ({} of {} participants improved).".format(
                  fmt(q["pre_mean"]), fmt(q["post_mean"]), q["improved"], q["pairs"]), "",
              "| Question | Right before | Right after |", "|---|---|---|"]
    for item in q["per_question"]:
        lines.append("| Q{} | {}% | {}% |".format(item["question"], fmt(item["pre_pct"], 0), fmt(item["post_pct"], 0)))
    u = s["sus"]
    lines += ["", "## Usability (System Usability Scale, 0-100)", "",
              "Mean SUS **{}** ({}), range {}-{}. 68 is the usual average.".format(
                  fmt(u["mean"]), u["label"] or "n/a", fmt(u["min"], 0), fmt(u["max"], 0)), "",
              "## Learning statements (1-5)", ""]
    names = {11: "Levels made it clear where to start",
             12: "Pictures, animation and charts helped understanding",
             13: "Could explain the speed tradeoffs to a classmate"}
    for item in s["learning"]:
        lines.append("- {}: **{}**".format(names[item["item"]], fmt(item["mean"])))
    if s["comments"]:
        lines += ["", "## Comments", ""]
        for c in s["comments"]:
            lines.append("- " + c)
    return "\n".join(lines) + "\n"


def make_chart(s, path):
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        return False
    fig, (left, right) = plt.subplots(1, 2, figsize=(11, 4), gridspec_kw={"width_ratios": [1.6, 1]})
    names = [t["key"].upper() for t in s["tasks"]]
    success = [t["success"] for t in s["tasks"]]
    hint = [t["hint"] for t in s["tasks"]]
    fail = [t["fail"] for t in s["tasks"]]
    gap = {"edgecolor": "white", "linewidth": 1.5}
    left.barh(names, success, color="#199e70", label="success", **gap)
    left.barh(names, hint, left=success, color="#f5b83d", label="with hint", **gap)
    left.barh(names, fail, left=[a + b for a, b in zip(success, hint)], color="#d95926", label="failed", **gap)
    left.invert_yaxis()
    left.set_xlabel("participants")
    left.set_title("Task completion")
    left.legend(frameon=False, ncol=3, loc="upper center", bbox_to_anchor=(0.5, -0.18))
    q = s["quiz"]
    if q["pre_mean"] is not None:
        right.bar(["before", "after"], [q["pre_mean"], q["post_mean"]], color=["#6d7fa8", "#3987e5"])
        right.set_ylim(0, QUIZ)
    right.set_ylabel("quiz score (out of %d)" % QUIZ)
    right.set_title("Quiz before vs after using the site")
    for axis in (left, right):
        axis.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(path, dpi=160)
    plt.close(fig)
    return True


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: python docs/evaluation/analyze.py <results.csv>")
    csv_path = Path(sys.argv[1])
    with open(csv_path, newline="", encoding="utf-8") as f:
        rows = [r for r in csv.DictReader(f) if r.get("participant", "").strip()]
    if not rows:
        sys.exit("no participants in " + str(csv_path))
    summary = summarize(rows)
    out_md = csv_path.with_name("summary.md")
    out_md.write_text(to_markdown(summary), encoding="utf-8")
    print("wrote", out_md)
    if make_chart(summary, csv_path.with_name("summary.png")):
        print("wrote", csv_path.with_name("summary.png"))


if __name__ == "__main__":
    main()
